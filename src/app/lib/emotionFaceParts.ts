/**
 * 감정 얼굴 부품 카탈로그 — 24×24 한 칸 안에서 얼굴·눈·눈썹·코·입·덧그림을 조합한다.
 *
 * 규칙
 * - 부품 번호(배열 순서)는 한 번 정하면 바꾸거나 다시 쓰지 않는다. 새 부품은 배열 맨 뒤에만 추가한다.
 *   (기록에 `f1e1b0n0m1x0`처럼 번호가 저장되므로, 번호가 바뀌면 옛 기록의 얼굴이 달라진다.)
 * - 모든 부품은 같은 24×24 좌표계를 쓴다. 눈 y≈10, 코 y≈11.7, 입 y≈13~16이 기준 위치다.
 * - v(긍정·부정)와 a(차분·흥분)는 -1~1 값으로, 얼굴이 어떤 감정으로 읽히는지 계산하는 데 쓴다.
 *
 * 색은 Figma emotion 아이콘(711:349~352) 원본 값을 그대로 옮긴 일러스트 고유 색이라
 * 디자인 토큰이 아니다(아이콘 SVG 파일과 같은 방식).
 */

export type SvgNode = {
  tag: "path" | "ellipse" | "circle" | "rect";
  /** React 속성 이름(camelCase) 그대로 */
  attrs: Record<string, string | number>;
  /** 있으면 이 값을 표준편차로 가우시안 블러를 적용한다. */
  blur?: number;
};

export type EmotionPart = {
  name: string;
  /** 긍정(+)·부정(-) 기여도 */
  v: number;
  /** 흥분(+)·차분(-) 기여도 */
  a: number;
  nodes: SvgNode[];
};

export type FacePart = EmotionPart & {
  /** 얼굴 윤곽 — 나머지 부품은 이 윤곽 안으로 잘린다. */
  d: string;
  fill: string;
};

export type ExtraPart = EmotionPart & {
  /** true면 눈·입 아래(바탕)에, false면 위에 그린다. */
  under: boolean;
};

