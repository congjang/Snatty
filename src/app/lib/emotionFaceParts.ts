const path = (d: string, fill: string, extra: Record<string, string | number> = {}): SvgNode => ({
  tag: "path",
  attrs: { d, fill, ...extra },
});
const line = (d: string, color: string, width: number, extra: Record<string, string | number> = {}): SvgNode => ({
  tag: "path",
  attrs: { d, fill: "none", stroke: color, strokeWidth: width, strokeLinecap: "round", strokeLinejoin: "round", ...extra },
});
const circle = (cx: number, cy: number, r: number, fill: string, extra: Record<string, string | number> = {}): SvgNode => ({
  tag: "circle",
  attrs: { cx, cy, r, fill, ...extra },
});
const ellipse = (cx: number, cy: number, rx: number, ry: number, fill: string, extra: Record<string, string | number> = {}): SvgNode => ({
  tag: "ellipse",
  attrs: { cx, cy, rx, ry, fill, ...extra },
});
const rect = (x: number, y: number, width: number, height: number, rx: number, fill: string): SvgNode => ({
  tag: "rect",
  attrs: { x, y, width, height, rx, fill },
});

